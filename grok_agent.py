def execute_mcp_tool_through_firewall(tool_name, arguments):
    """
    Routes an LLM tool call through TrueIntent's 4-layer eBPF inspection pipeline
    and executes it on the local MCP server if allowed.
    """
    req_id = int(time.time() * 1000) % 1000000

    print(f"\n{BOLD}{CYAN}------------------------------------------------------------------------{RESET}")
    print(f"[*] {BOLD}MCP TOOL CALL GENERATED BY GROK:{RESET} {CYAN}{tool_name}{RESET}")
    print(f"[*] {BOLD}ARGUMENTS:{RESET} {json.dumps(arguments)}")
    print(f"{BOLD}{CYAN}------------------------------------------------------------------------{RESET}")

    # --- Layer 1: Policy Engine ---
    pol_action, pol_reason = policy_adapter.evaluate_tool_call(tool_name, arguments)
    print(f"{BOLD}[Layer 1: Policy & Capability Check]{RESET}")
    if pol_action == "block":
        print(f"  {RED}⛔ POLICY BLOCK: {pol_reason}{RESET}")
        notify_server_block(req_id)
        return {
            "status": "error",
            "error": f"Security Policy Violation: {pol_reason}",
            "blocked": True,
            "layer": "Layer 1 (Policy Engine)"
        }
    else:
        print(f"  {GREEN}✓ Capability Checked: Allowed by policy schema{RESET}")

    # --- Layer 2: Deobfuscation Engine ---
    deobf_args = {}
    has_obf = False
    for k, v in arguments.items():
        if isinstance(v, str):
            deobf_v = deobfuscator.deobfuscate(v)
            deobf_args[k] = deobf_v
            if deobf_v != v:
                has_obf = True

    print(f"{BOLD}[Layer 2: De-obfuscation Engine]{RESET}")
    if has_obf:
        print(f"  {YELLOW}⚠ Obfuscation/Encoding Detected! Unmasked payload:{RESET}")
        for k, v in arguments.items():
            if v != deobf_args.get(k):
                print(f"    ↳ {k}: {GREEN}{deobf_args.get(k)}{RESET}")
    else:
        print(f"  {GREEN}✓ Payload clean (no evasion encodings){RESET}")

    # --- Layer 3: Semantic Threat Inspector ---
    sem_decision, sem_reason, sem_details = detector.check_arguments(arguments)
    print(f"{BOLD}[Layer 3: Semantic Threat Inspector]{RESET}")
    if sem_decision == "flag":
        print(f"  {RED}🚨 THREAT DETECTED: {sem_reason}{RESET}")
        for d in sem_details.get("detections", []):
            print(f"    • {BOLD}{d.get('description')}{RESET} matched: `{d.get('matched')}`")
        notify_server_block(req_id)
        print(f"  ↳ Dispatched out-of-band block signal to IPS control (:8444) for Request ID {req_id}")
    else:
        print(f"  {GREEN}✓ Semantic scan clean{RESET}")

    # --- Layer 4: Real-time Server Enforcement (IPS) ---
    print(f"{BOLD}[Layer 4: Local MCP Server Execution & IPS Enforcement]{RESET}")
    mcp_body = json.dumps({
        "jsonrpc": "2.0",
        "id": req_id,
        "method": "tools/call",
        "params": {
            "name": tool_name,
            "arguments": arguments
        }
    }).encode("utf-8")

    req = urllib.request.Request(
        MCP_SERVER_URL,
        data=mcp_body,
        headers={
            "Content-Type": "application/json",
            "X-API-Key": MCP_API_KEY
        }
    )

    try:
        with urllib.request.urlopen(req, context=ssl_ctx, timeout=5) as response:
            body = response.read().decode('utf-8', errors='ignore')
            print(f"  {GREEN}✔ HTTP 200 OK - Execution Completed Safely{RESET}")
            try:
                parsed = json.loads(body)
                return parsed.get("result", {})
            except Exception:
                return {"output": body}
    except urllib.error.HTTPError as e:
        body = e.read().decode('utf-8', errors='ignore') if e.fp else ""
        if e.code == 403:
            print(f"  {RED}⛔ HTTP 403 FORBIDDEN - BLOCKED BY TRUEINTENT IPS{RESET}")
            print(f"  Server Payload: {RED}{body}{RESET}")
            return {
                "status": "blocked",
                "error": "CRITICAL: Tool call terminated by TrueIntent eBPF Firewall (HTTP 403 Forbidden).",
                "blocked": True
            }
        else:
            print(f"  {YELLOW}⚠ Server HTTP {e.code}: {body}{RESET}")
            return {"error": f"HTTP {e.code}: {body}"}
    except Exception as e:
        print(f"  {RED}⚠ Connection Error to MCP server: {e}{RESET}")
        return {"error": str(e)}

def call_grok_api(messages):
    """Calls xAI Grok API using OpenAI-compatible chat completion endpoint"""
    url = f"{GROK_BASE_URL.rstrip('/')}/chat/completions"
    
    payload = {
        "model": GROK_MODEL,
        "messages": messages,
        "tools": MCP_TOOLS_SPEC,
        "tool_choice": "auto",
        "temperature": 0.2
    }

    req = urllib.request.Request(
        url,
        data=json.dumps(payload).encode('utf-8'),
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {GROK_API_KEY}"
        }
    )

    try:
        with urllib.request.urlopen(req, timeout=30) as response:
            return json.loads(response.read().decode('utf-8'))
    except urllib.error.HTTPError as e:
        err_msg = e.read().decode('utf-8', errors='ignore') if e.fp else str(e)
        raise RuntimeError(f"Grok API Error (HTTP {e.code}): {err_msg}")
    except Exception as e:
        raise RuntimeError(f"Network error calling Grok API: {e}")

def run_agent_turn(user_prompt, conversation_history):
    """Processes a user prompt through Grok and handles tool calls"""
    conversation_history.append({"role": "user", "content": user_prompt})
    print(f"\n{BOLD}{GREEN}User:{RESET} {user_prompt}")
    print(f"{DIM}[*] Sending prompt to Grok ({GROK_MODEL})...{RESET}")

    try:
        response = call_grok_api(conversation_history)
    except Exception as e:
        print(f"{RED}[Error calling Grok]: {e}{RESET}")
        return

    choice = response["choices"][0]
    message = choice["message"]
    conversation_history.append(message)

    # Check if Grok wants to call MCP tools
    tool_calls = message.get("tool_calls", [])
    if tool_calls:
        for tool_call in tool_calls:
            t_id = tool_call.get("id", "call_1")
            fn = tool_call.get("function", {})
            t_name = fn.get("name")
            try:
                t_args = json.loads(fn.get("arguments", "{}"))
            except Exception:
                t_args = {}

            # Execute tool through TrueIntent
            tool_result = execute_mcp_tool_through_firewall(t_name, t_args)

            # Send tool result back to Grok
            conversation_history.append({
                "role": "tool",
                "tool_call_id": t_id,
                "name": t_name,
                "content": json.dumps(tool_result)
            })

        # Get final response from Grok after tool execution
        print(f"\n{DIM}[*] Getting final response from Grok...{RESET}")
        try:
            final_resp = call_grok_api(conversation_history)
            final_content = final_resp["choices"][0]["message"].get("content", "")
            print(f"\n{BOLD}{CYAN}Grok Assistant:{RESET} {final_content}")
            conversation_history.append(final_resp["choices"][0]["message"])
        except Exception as e:
            print(f"{RED}[Error getting final response]: {e}{RESET}")
    else:
        # Normal text response
        content = message.get("content", "")
        print(f"\n{BOLD}{CYAN}Grok Assistant:{RESET} {content}")

